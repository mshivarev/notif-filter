package ru.notiffilter.classify

/** Одно правило: человекочитаемая метка, регулярка по нормализованному тексту и вес. */
class Rule(val label: String, pattern: String, val weight: Int) {
    val regex = Regex(pattern)
}

/** Начало слова: перед ним не буква и не цифра (работает и для кириллицы, в отличие от \b). */
private const val W = "(?<![\\p{L}\\p{N}])"
private const val END = "(?![\\p{L}\\p{N}])"

object Rules {

    /** Правила для текста уведомления (заголовок + текст). */
    val text: List<Rule> = listOf(
        // --- Сильные признаки рекламы ---
        Rule("скидка", "${W}скид(к|оч)", 3),
        Rule("акция", "${W}акци(?!онер)|${W}акцион", 3),
        Rule("распродажа", "${W}распродаж", 3),
        Rule("промокод", "${W}промо[- ]?код|${W}promo ?code", 3),
        Rule("кешбэк", "${W}(кешб|кэшб|cashback)", 3),
        Rule("sale", "${W}(sale|discount|promo)$END", 3),
        Rule("только сегодня", "${W}только (сегодня|до|в эти|сейчас)", 3),
        Rule("успейте", "${W}успе(й|йте|ть купить|ть заказать)$END", 3),
        Rule("спецпредложение", "${W}спец\\.? ?предлож|${W}специальн(ое|ая|ые) (предлож|цен)", 3),
        Rule("бесплатная доставка", "${W}бесплатн(ая|ую|ой) доставк|${W}free (shipping|delivery)", 3),
        Rule("чёрная пятница", "${W}черн(ая|ой|ую) пятниц|${W}black friday|${W}киберпонедельник|${W}11\\.11", 3),
        Rule("−N%", "(-|−|–|минус ?)\\d{1,2} ?%|${W}до \\d{1,2} ?%|\\d{1,2} ?% (off|скид|дешевле)", 3),
        Rule("цена снижена", "${W}(цен[аы]|стоимост\\w*) (снижен|упал)|${W}снизили цен|${W}по сниженн", 3),
        Rule("₽ вместо", "\\d ?(₽|р\\.?|руб\\w*) вместо", 3),

        // --- Средние ---
        Rule("предложение", "${W}предложени|${W}(offer|deal)s?$END", 2),
        Rule("выгода", "${W}выгод", 2),
        Rule("подарок", "${W}(подар(ок|ки|ка|им|ите|ков)|дарим)$END|${W}в подарок", 2),
        Rule("бонусы/баллы", "${W}(бонус|балл(ов|ы|ами)$END)", 2),
        Rule("купон", "${W}(купон|coupon)", 2),
        Rule("новинки", "${W}новинк|${W}new arrivals?", 2),
        Rule("не пропустите", "${W}не пропусти|${W}последний шанс|${W}last chance|${W}don.?t miss", 2),
        Rule("лучшие цены", "${W}(лучш|низк|выгодн|супер|мега)\\w* цен", 2),
        Rule("ограничено", "${W}ограниченн|${W}limited|${W}осталось (всего )?\\d+ (час|дн|дня|дней)|${W}заканчива(ет|ют)ся", 2),
        Rule("розыгрыш", "${W}розыгрыш|${W}выигра(й|йте|ть)|${W}разыгрыва", 3),
        Rule("конкурс", "${W}конкурс|${W}участву(й|йте)$END", 2),
        Rule("для вас", "${W}(специально |только )?для вас$END|${W}персональн\\w* (предлож|скид|подбор)", 2),
        Rule("хит продаж", "${W}хит(ы)? продаж|${W}бестселлер|${W}топ товар", 3),
        Rule("купите/закажите", "${W}(купи(те)?|закажи(те)?|покупай(те)?|оформи(те)?)$END|${W}shop now|${W}buy now", 2),

        // --- Слабые ---
        Rule("подборка", "${W}подборк|${W}рекомендуем|${W}вам понрав|${W}смотрите что|${W}загляни", 1),
        Rule("цена", "\\d ?(₽|руб)", 1),

        // --- Антипризнаки (служебные уведомления) ---
        Rule("код подтверждения", "${W}код\\w*( подтвержд| для вход| верифик| доступ|:|\\s+\\d{3,})|${W}(verification|security|one.time) code|${W}пароль", -6),
        Rule("статус заказа", "${W}(ваш )?заказ (№|#|n|\\d|доставл|прибыл|собран|передан|готов|отмен|оформлен|ожидает|оплачен|принят)|${W}курьер|${W}доставлен|${W}пункт(е)? выдачи|${W}трек.?номер|${W}order (#|\\d|shipped|delivered)", -5),
        Rule("деньги", "${W}(списани|списан|оплат(а|ил|ен)|перевод|зачислен|начислен|поступлени|пополнени|баланс|покупка на|платеж|транзакц)", -4),
        Rule("безопасность", "${W}(вход в (аккаунт|прилож)|новый вход|новое устройство|подозрительн|заблокир)", -5),
        Rule("звонок", "${W}(пропущенн\\w* (вызов|звон)|входящ\\w* вызов|missed call)", -6),
        Rule("напоминание", "${W}(напоминани|запись на|ваш визит|бронирован|рейс|посадк|билет)", -2),
    )

    /** Правила для id/имени канала уведомления. */
    val channel: List<Rule> = listOf(
        Rule("канал рекламы", "promo|marketing|advert|offer|deal|sale|campaign|реклам|акци|маркетинг|предложен|скидк|рассылк|спецпредлож", 4),
    )

    /** Эмодзи, типичные для рекламы. */
    val promoEmoji = listOf("🔥", "🎁", "💥", "⚡", "🛍", "💸", "🤑", "🎉", "🛒", "💰", "🏷", "😍", "❗", "‼")
}
